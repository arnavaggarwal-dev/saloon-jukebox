/**
 * Concatenates every migration plus the seed into `supabase/setup.sql`, so the
 * whole database can be created with one paste into the Supabase SQL editor.
 *
 * Run it after adding a migration:  node scripts/build-setup-sql.mjs
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const migrationsDir = resolve(root, 'supabase/migrations');

const migrations = readdirSync(migrationsDir)
  .filter((f) => f.endsWith('.sql'))
  .sort(); // 001_, 002_, … apply in order

const header = `-- =====================================================================
-- Saloon Jukebox — complete setup (schema + library seed).
--
-- Paste this whole file into the Supabase SQL editor and press Run.
-- Safe to run more than once, and safe to re-run after pulling changes.
--
-- Generated by scripts/build-setup-sql.mjs from:
${migrations.map((m) => `--   supabase/migrations/${m}`).join('\n')}
--   supabase/seed.sql
-- =====================================================================
`;

const body = [
  ...migrations.map((m) => readFileSync(resolve(migrationsDir, m), 'utf8')),
  readFileSync(resolve(root, 'supabase/seed.sql'), 'utf8'),
].join('\n');

writeFileSync(resolve(root, 'supabase/setup.sql'), `${header}\n${body}`);
console.log(`Wrote supabase/setup.sql from ${migrations.length} migration(s) + seed.`);
